/**
 * One file for the Supabase dashboard.
 *
 * `supabase/functions/notify-order` is three modules on purpose — the message
 * and the delivery logic have no runtime of their own, which is what lets
 * `npm run check:notify` exercise them under Node. The dashboard's browser
 * editor, though, wants one file pasted into one box. This joins the three,
 * in dependency order, with the relative imports removed.
 *
 *   npm run bundle:notify   →   supabase/dashboard/notify-order.ts
 *
 * Generated, never edited: change the modules and run this again. The CLI path
 * (`supabase functions deploy notify-order`) deploys the modules themselves and
 * does not need this at all.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "supabase/functions/notify-order");
const target = join(root, "supabase/dashboard/notify-order.ts");

const RELATIVE_IMPORT = /^import\s[^;]*from\s+["']\.\/[^"']+["'];\s*$/gm;
const REMOTE_IMPORT = /^import\s[^;]*from\s+["'](?:jsr|npm|https?):[^"']+["'];\s*$/gm;

const read = (name) => readFile(join(source, name), "utf8");
const [message, push, deliver, index] = await Promise.all([
  read("message.ts"),
  read("push.ts"),
  read("deliver.ts"),
  read("index.ts"),
]);

// The one import that survives, hoisted to the top where Deno expects it.
const remote = [...index.matchAll(REMOTE_IMPORT)].map((match) => match[0].trim());
const strip = (text) => text.replace(RELATIVE_IMPORT, "").replace(REMOTE_IMPORT, "").trim();

const banner = `/**
 * notify-order — single-file build for the Supabase dashboard editor.
 *
 * GENERATED by scripts/bundle-notify.mjs from supabase/functions/notify-order/
 * (message.ts, push.ts, deliver.ts, index.ts). Do not edit this file: edit those and run
 * \`npm run bundle:notify\`.
 */`;

const output = [
  banner,
  remote.join("\n"),
  "// ── message.ts ──────────────────────────────────────────────────────────────",
  strip(message),
  "// ── push.ts ─────────────────────────────────────────────────────────────────",
  strip(push),
  "// ── deliver.ts ──────────────────────────────────────────────────────────────",
  strip(deliver),
  "// ── index.ts ────────────────────────────────────────────────────────────────",
  strip(index),
].join("\n\n");

await mkdir(dirname(target), { recursive: true });
await writeFile(target, `${output}\n`);
console.log(`written ${target.replace(`${root}/`, "")} — ${output.split("\n").length} lines`);
